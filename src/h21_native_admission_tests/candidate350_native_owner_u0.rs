#[repr(C)]
#[derive(Clone, Copy, Default)]
struct FileTime {
    low: u32,
    high: u32,
}

#[link(name = "kernel32")]
extern "system" {
    fn GetCurrentProcess() -> *mut std::ffi::c_void;
    fn GetProcessTimes(
        process: *mut std::ffi::c_void,
        creation: *mut FileTime,
        exit: *mut FileTime,
        kernel: *mut FileTime,
        user: *mut FileTime,
    ) -> i32;
}

fn process_cpu_100ns() -> Result<u64, String> {
    let mut creation = FileTime::default();
    let mut exit = FileTime::default();
    let mut kernel = FileTime::default();
    let mut user = FileTime::default();
    let ok = unsafe {
        GetProcessTimes(
            GetCurrentProcess(),
            &mut creation,
            &mut exit,
            &mut kernel,
            &mut user,
        )
    };
    if ok == 0 {
        return Err("GetProcessTimes failed".into());
    }
    let ticks = |time: FileTime| ((time.high as u64) << 32) | time.low as u64;
    ticks(kernel)
        .checked_add(ticks(user))
        .ok_or_else(|| "process CPU counter overflow".into())
}

fn timing(
    name: &str,
    owner: Option<usize>,
    wall: std::time::Instant,
    cpu: u64,
) -> Result<(), String> {
    let cpu_ns = process_cpu_100ns()?
        .checked_sub(cpu)
        .ok_or("process CPU counter regressed")?
        .checked_mul(100)
        .ok_or("process CPU nanosecond overflow")?;
    println!(
        "C350_STAGE name={name} owner={owner:?} wall_ns={} process_cpu_ns={cpu_ns}",
        wall.elapsed().as_nanos()
    );
    Ok(())
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn input_from_row(row: &NativePackedRow) -> Result<Vec<Fr>, String> {
    if row.packed_bytes().len() != OWNER_WIDTH / 8 {
        return Err("C350 packed X row length".into());
    }
    let mut input = Vec::with_capacity(OWNER_WIDTH);
    for wire in 0..OWNER_WIDTH {
        input.push(Fr::from(
            ((row.packed_bytes()[wire / 8] >> (wire % 8)) & 1) as u64,
        ));
    }
    if input.len() != OWNER_WIDTH || input.iter().any(|x| !x.is_zero() && !x.is_one()) {
        return Err("C350 native expanded X is not Boolean".into());
    }
    Ok(input)
}

/// Dense, direct row-equality oracle. It does not use the Boolean-U bank or
/// the production sparse direct-coefficient helper.
fn dense_u0_oracle(
    template: &[crate::sparse::Term],
    row_weights: &[Fr],
    input: &[Fr],
    owner_factor: Fr,
) -> Result<[Fr; 3], String> {
    if row_weights.len() != OWNER_ROWS || input.len() != OWNER_WIDTH {
        return Err("C350 dense oracle dimensions".into());
    }
    let mut a = vec![Fr::zero(); OWNER_WIDTH];
    let mut b = vec![Fr::zero(); OWNER_WIDTH];
    for term in template {
        if term.row >= OWNER_ROWS || term.gate.left >= OWNER_WIDTH || term.gate.right >= OWNER_WIDTH
        {
            return Err("C350 dense oracle term bounds".into());
        }
        // Keep both dimensions in the independent per-term product. The
        // 19-bit row table is generated by direct bit-coordinate products;
        // the caller's owner factor is the separate direct 21-bit product.
        let weight = row_weights[term.row] * owner_factor;
        let right = input[term.gate.right];
        a[term.gate.left] += weight * (term.gate.c1 + term.gate.c3 * right);
        b[term.gate.left] += weight * (term.gate.c0 + term.gate.c2 * right);
    }
    let message: [Fr; 3] = crate::gkr::quadratic_message(&a, &b, input)
        .try_into()
        .map_err(|_| "C350 dense oracle message width")?;
    Ok(message)
}

/// Independent scalar row × owner × one-bit-prefix product oracle. Selectors
/// read original X; only the final message sees X folded at the fixed point.
struct C351DenseU1 {
    a: Vec<Fr>,
    b: Vec<Fr>,
    message: [Fr; 3],
}

fn c351_dense_u1_oracle(
    template: &[crate::sparse::Term],
    point: &[Fr],
    owner: usize,
    factor_owner: usize,
    input: &[Fr],
    alpha: Fr,
) -> Result<C351DenseU1, String> {
    if point.len() != 40
        || input.len() != OWNER_WIDTH
        || template.len() != 396_561
        || owner >= (1 << 21)
        || factor_owner >= (1 << 21)
    {
        return Err("C351 dense dimensions".into());
    }
    let mut a = vec![Fr::zero(); OWNER_WIDTH / 2];
    let mut b = vec![Fr::zero(); OWNER_WIDTH / 2];
    for term in template {
        if term.row >= OWNER_ROWS || term.gate.left >= OWNER_WIDTH || term.gate.right >= OWNER_WIDTH
        {
            return Err("C351 dense term bounds".into());
        }
        let mut row_eq = Fr::one();
        for bit in 0..19 {
            row_eq *= if ((term.row >> bit) & 1) == 1 {
                point[bit]
            } else {
                Fr::one() - point[bit]
            };
        }
        let mut owner_eq = Fr::one();
        for bit in 0..21 {
            owner_eq *= if ((factor_owner >> bit) & 1) == 1 {
                point[19 + bit]
            } else {
                Fr::one() - point[19 + bit]
            };
        }
        let prefix_eq = if term.gate.left & 1 == 1 {
            alpha
        } else {
            Fr::one() - alpha
        };
        let weight = row_eq * owner_eq * prefix_eq;
        let right = input[term.gate.right];
        let bucket = term.gate.left >> 1;
        a[bucket] += weight * (term.gate.c1 + term.gate.c3 * right);
        b[bucket] += weight * (term.gate.c0 + term.gate.c2 * right);
    }
    let folded: Vec<Fr> = (0..OWNER_WIDTH / 2)
        .map(|i| (Fr::one() - alpha) * input[2 * i] + alpha * input[2 * i + 1])
        .collect();
    let message: [Fr; 3] = crate::gkr::quadratic_message(&a, &b, &folded)
        .try_into()
        .map_err(|_| "C351 dense message width")?;
    Ok(C351DenseU1 { a, b, message })
}

fn direct_eq_weights(point: &[Fr]) -> Result<Vec<Fr>, String> {
    if point.len() >= usize::BITS as usize {
        return Err("C350 direct equality point width".into());
    }
    let count = 1usize << point.len();
    let mut weights = Vec::with_capacity(count);
    for index in 0..count {
        let mut weight = Fr::one();
        for (bit, coordinate) in point.iter().enumerate() {
            weight *= if ((index >> bit) & 1) == 1 {
                *coordinate
            } else {
                Fr::one() - *coordinate
            };
        }
        weights.push(weight);
    }
    Ok(weights)
}

fn record_unresolved_relation(
    counts: &mut Vec<(Relation, usize, usize)>,
    relation: Relation,
    foreign: bool,
) -> Result<(), String> {
    let entry = counts
        .iter_mut()
        .find(|(known, _, _)| *known == relation)
        .map(|(_, foreign_count, local_count)| (foreign_count, local_count));
    let (foreign_count, local_count) = match entry {
        Some(counts) => counts,
        None => {
            counts.push((relation, 0, 0));
            let (_, foreign_count, local_count) =
                counts.last_mut().ok_or("C350 unresolved relation record")?;
            (foreign_count, local_count)
        }
    };
    let count = if foreign { foreign_count } else { local_count };
    *count = count
        .checked_add(1)
        .ok_or("C350 unresolved relation count overflow")?;
    Ok(())
}

fn normalized_template(
    roster: &DaaHistoryRoster<'_>,
    owner: usize,
) -> Result<Vec<crate::sparse::Term>, String> {
    let row_base = owner
        .checked_mul(OWNER_ROWS)
        .ok_or("C350 row base overflow")?;
    let wire_base = owner
        .checked_mul(OWNER_WIDTH)
        .ok_or("C350 wire base overflow")?;
    let mut terms = Vec::new();
    let counts = roster.visit_header_terms(owner as u64, |mut term| {
        term.row = term
            .row
            .checked_sub(row_base)
            .ok_or("C350 normalized row underflow")?;
        term.gate.left = term
            .gate
            .left
            .checked_sub(wire_base)
            .ok_or("C350 normalized left underflow")?;
        term.gate.right = term
            .gate
            .right
            .checked_sub(wire_base)
            .ok_or("C350 normalized right underflow")?;
        terms.push(term);
        Ok(())
    })?;
    if counts.emitted != terms.len() {
        return Err("C350 source/template count mismatch".into());
    }
    Ok(terms)
}

fn visit_normalized_owner_terms(
    roster: &DaaHistoryRoster<'_>,
    owner: usize,
    expected: &[crate::sparse::Term],
    mut mutate: impl FnMut(usize, &mut crate::sparse::Term),
    mut sink: impl FnMut(crate::sparse::Term) -> Result<(), String>,
) -> Result<(), String> {
    let row_base = owner
        .checked_mul(OWNER_ROWS)
        .ok_or("C350 mutant row base overflow")?;
    let wire_base = owner
        .checked_mul(OWNER_WIDTH)
        .ok_or("C350 mutant wire base overflow")?;
    let mut term_index = 0usize;
    let counts = roster.visit_header_terms(owner as u64, |mut term| {
        term.row = term
            .row
            .checked_sub(row_base)
            .ok_or("C350 mutant row underflow")?;
        term.gate.left = term
            .gate
            .left
            .checked_sub(wire_base)
            .ok_or("C350 mutant left underflow")?;
        term.gate.right = term
            .gate
            .right
            .checked_sub(wire_base)
            .ok_or("C350 mutant right underflow")?;
        if expected.get(term_index) != Some(&term) {
            return Err(format!(
                "C350 mutant source template drift owner={owner} index={term_index}"
            ));
        }
        mutate(term_index, &mut term);
        term_index = term_index
            .checked_add(1)
            .ok_or("C350 mutant term count overflow")?;
        sink(term)
    })?;
    if counts.emitted != term_index || term_index != expected.len() {
        return Err(format!("C350 mutant source term count drift owner={owner}"));
    }
    Ok(())
}

fn template_digest(terms: &[crate::sparse::Term]) -> Result<String, String> {
    let mut bytes = Vec::with_capacity(terms.len() * 152);
    for term in terms {
        bytes.extend_from_slice(
            &u64::try_from(term.row)
                .map_err(|_| "C350 template row width")?
                .to_le_bytes(),
        );
        bytes.extend_from_slice(
            &u64::try_from(term.gate.left)
                .map_err(|_| "C350 template left width")?
                .to_le_bytes(),
        );
        bytes.extend_from_slice(
            &u64::try_from(term.gate.right)
                .map_err(|_| "C350 template right width")?
                .to_le_bytes(),
        );
        for coefficient in [term.gate.c0, term.gate.c1, term.gate.c2, term.gate.c3] {
            ark_serialize::CanonicalSerialize::serialize_compressed(&coefficient, &mut bytes)
                .map_err(|error| format!("C350 coefficient encoding: {error}"))?;
        }
    }
    Ok(hex(&role0_sha256(&bytes)?))
}

fn c352_sorted_unique_edges(
    edges: &[(usize, usize)],
    shift_left: bool,
) -> Result<Vec<(usize, usize)>, String> {
    let mut keys = Vec::with_capacity(edges.len());
    for &(left, right) in edges {
        if left >= OWNER_WIDTH || right >= OWNER_WIDTH {
            return Err("C352 edge coordinate outside owner width".into());
        }
        keys.push((if shift_left { left >> 1 } else { left }, right));
    }
    keys.sort_unstable();
    keys.dedup();
    Ok(keys)
}

fn c352_ordered_unique_edges(
    edges: &[(usize, usize)],
    shift_left: bool,
) -> Result<BTreeSet<(usize, usize)>, String> {
    let mut keys = BTreeSet::new();
    for &(left, right) in edges {
        if left >= OWNER_WIDTH || right >= OWNER_WIDTH {
            return Err("C352 edge coordinate outside owner width".into());
        }
        keys.insert((if shift_left { left >> 1 } else { left }, right));
    }
    Ok(keys)
}

fn c352_checked_edge_support(
    edges: &[(usize, usize)],
    shift_left: bool,
) -> Result<Vec<(usize, usize)>, String> {
    let sorted = c352_sorted_unique_edges(edges, shift_left)?;
    let ordered = c352_ordered_unique_edges(edges, shift_left)?;
    if ordered.len() != sorted.len() || !ordered.iter().copied().eq(sorted.iter().copied()) {
        return Err("C352 sorted-vector/BTreeSet edge support differs".into());
    }
    Ok(sorted)
}

fn c352_edge_support_fixtures() -> Result<(), String> {
    let duplicates = [(4, 9), (4, 9), (5, 9)];
    if c352_checked_edge_support(&duplicates, false)? != vec![(4, 9), (5, 9)] {
        return Err("C352 duplicate-collapse fixture".into());
    }

    let low_left_pair = [(8, 3), (9, 3)];
    if c352_checked_edge_support(&low_left_pair, false)?.len() != 2
        || c352_checked_edge_support(&low_left_pair, true)? != vec![(4, 3)]
    {
        return Err("C352 U1 low-left-bit collapse fixture".into());
    }

    let right_before = [(4, 3)];
    let right_after = [(4, 4)];
    if c352_checked_edge_support(&right_before, false)?
        == c352_checked_edge_support(&right_after, false)?
        || c352_checked_edge_support(&right_before, true)?
            == c352_checked_edge_support(&right_after, true)?
    {
        return Err("C352 right-coordinate support fixture".into());
    }

    let out_of_range = [(OWNER_WIDTH, 0)];
    let right_out_of_range = [(0, OWNER_WIDTH)];
    if c352_checked_edge_support(&out_of_range, false).is_ok()
        || c352_checked_edge_support(&out_of_range, true).is_ok()
        || c352_checked_edge_support(&right_out_of_range, false).is_ok()
        || c352_checked_edge_support(&right_out_of_range, true).is_ok()
    {
        return Err("C352 out-of-range coordinate fixture".into());
    }
    Ok(())
}

fn c352_edge_support(terms: &[crate::sparse::Term]) -> Result<(usize, usize), String> {
    if terms.len() != 396_561 {
        return Err("C352 Carry template term count".into());
    }
    let mut edges = Vec::with_capacity(terms.len());
    for term in terms {
        edges.push((term.gate.left, term.gate.right));
    }
    let e0 = c352_checked_edge_support(&edges, false)?.len();
    let e1 = c352_checked_edge_support(&edges, true)?.len();
    if e0 == 0 || e1 == 0 || e1 > e0 || e0 > terms.len() {
        return Err("C352 edge-support cardinality bounds".into());
    }
    Ok((e0, e1))
}

